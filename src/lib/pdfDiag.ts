/**
 * ATTEMPT COMPARISON — for the reported "first open fails, second open of the same file succeeds".
 *
 * A ledger per attempt is not enough to answer that: the question is what was DIFFERENT. This puts
 * the attempts side by side — how far each got, where each stopped, and how long each stage took —
 * so the difference is read off the report rather than reasoned about. It states differences only;
 * it does not explain them, because the explanation is what the evidence is for.
 */
function renderAttemptComparison(): string {
  const all = [...archived.map((a) => ({ label: a.at, stages: a.stages })), { label: "most recent", stages: ledger.stages() }];
  const pdfOnly = all.filter((a) => String(a.stages.find((s) => s.key === "open.requested")?.meta?.format ?? "") === "pdf");
  const L: string[] = [];
  L.push("=".repeat(78));
  L.push("PDF ATTEMPT COMPARISON");
  L.push("=".repeat(78));
  L.push("");
  if (pdfOnly.length < 2) {
    L.push(`Only ${pdfOnly.length} PDF attempt was recorded in this session — there is nothing to compare.`);
    L.push("A second attempt on the SAME file is what makes the 'first fails, second works' report");
    L.push("answerable, so please open the failing PDF twice before saving the report.");
    L.push("");
    return L.join("\r\n");
  }
  const furthest = (st: Stage[]) => [...st].reverse().find((s) => s.state === "COMPLETED");
  const stopped = (st: Stage[]) => st.find((s) => s.state === "FAILED") ?? st.find((s) => s.state === "ENTERED");
  L.push("  #   furthest completed                     stopped at");
  pdfOnly.forEach((a, i) => {
    const f = furthest(a.stages), s = stopped(a.stages);
    L.push(
      `  ${String(i + 1).padEnd(3)} ${(f ? `${f.id} — ${f.title}` : "NONE").slice(0, 38).padEnd(38)} ` +
        `${s ? `${s.id} — ${s.title} (${s.state === "FAILED" ? "FAILED" : "never completed"})` : "nothing left unfinished"}`,
    );
  });
  L.push("");
  // Per-stage differences: the same stage, attempt by attempt. Only stages that DIFFER are printed —
  // a table of identical rows hides the one row that matters.
  L.push("  Stages whose outcome or duration DIFFERED between attempts:");
  let printed = 0;
  for (let i = 0; i < pdfOnly[0].stages.length; i++) {
    const cells = pdfOnly.map((a) => a.stages[i]);
    const states = cells.map((c) => c?.state ?? "NOT ENTERED");
    const times = cells.map((c) => (c?.enteredAt != null && c?.endedAt != null ? c.endedAt - c.enteredAt : null));
    const stateDiffers = new Set(states).size > 1;
    const timeDiffers = times.some((t, k) => k > 0 && t != null && times[0] != null && Math.abs(t - (times[0] ?? 0)) > 250);
    if (!stateDiffers && !timeDiffers) continue;
    printed++;
    L.push(`    Stage ${cells[0]?.id ?? i + 1} — ${cells[0]?.title ?? "?"}`);
    cells.forEach((c, k) => {
      L.push(`      attempt ${k + 1}: ${states[k]}${times[k] != null ? `  (${times[k]} ms)` : ""}` +
        (c?.error ? `  REASON: ${c.error.name}: ${c.error.message}` : ""));
    });
  }
  if (!printed) {
    L.push("    NONE — every stage reached the same outcome in the same time on every attempt.");
    L.push("    If one attempt failed and another succeeded, the difference is NOT in these stages.");
  }
  L.push("");
  return L.join("\r\n");
}

export function renderStages(): string {
  const parts: string[] = [];
  // Earlier attempts first, so the report reads in the order the tester lived it.
  archived.forEach((a, i) =>
    parts.push(renderStageList(`PDF PIPELINE — STAGE LEDGER — EARLIER ATTEMPT #${i + 1} (${a.label}, ${a.at})`, a.stages)),
  );
  // Name the most recent ledger by WHAT IT ACTUALLY IS. Every book open resets this ledger, so the
  // last one is often an EPUB — and an EPUB open shown under a "PDF PIPELINE" heading with stages
  // 8-13 reading NOT ENTERED reads exactly like a PDF that died at stage 8. Measured on a healthy
  // machine: opening a PDF twice and then an EPUB produced precisely that misleading page.
  const liveFormat = String(ledger.stages().find((s) => s.key === "open.requested")?.meta?.format ?? "");
  const liveTitle =
    liveFormat === "pdf"
      ? `PDF PIPELINE — STAGE LEDGER — MOST RECENT PDF ATTEMPT (attempt #${archived.length + 1})`
      : archived.length
        ? "MOST RECENT BOOK OPENED — NOT A PDF (stages 8-13 do not apply to it; the PDF attempts are above)"
        : "PDF PIPELINE — STAGE LEDGER";
  parts.push(ledger.render(liveTitle));
  parts.push(renderAttemptComparison());
  return parts.join("\r\n");
}

export const pdfStages = (): Stage[] => ledger.stages();
export const pdfAttempts = (): { at: string; label: string; stages: Stage[] }[] => archived;
